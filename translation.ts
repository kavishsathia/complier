// Translation units: pure maps between external events and the CSP alphabet.
// Input events come from the world (uncontrollable), output events from the agent (controllable).

import type { NotionTools } from "./gen/notion";

// ---- alphabet ----

type Event<T = unknown> = { channel: string; value: T };

type Channel<T> = ((value: T) => Event<T>) & { name: string };

function channel<T = void>(name: string): Channel<T> {
  return Object.assign((value: T) => ({ channel: name, value }), { name });
}

// ---- translation unit ----

type InputMap<P> = (payload: P) => Event;
type OutputMap<A> = (args: A) => Event;

// `Tools` is the tool map generated by `complier gen`, so tool names and arguments come from
// the server's own schemas. Input payloads are typed by hand: MCP declares no notification schemas.
class Unit<Tools extends Record<string, unknown>> {
  readonly inputs = new Map<string, InputMap<any>>();
  readonly outputs = new Map<string, OutputMap<any>>();
  readonly hidden = new Set<string>();

  constructor(readonly name: string) {}

  // An external event the world emits. Unregistered input events are dropped (fail open).
  input<P>(source: string, map: InputMap<P>): this {
    this.inputs.set(source, map);
    return this;
  }

  // An action the agent takes. Unregistered output events are refused (fail closed).
  output<K extends keyof Tools & string>(tool: K, map: OutputMap<Tools[K]>): this {
    this.outputs.set(tool, map);
    return this;
  }

  // Agent actions declared to have no effect on the modeled world.
  hide(...tools: (keyof Tools & string)[]): this {
    tools.forEach((t) => this.hidden.add(t));
    return this;
  }
}

function unit<Tools extends Record<string, unknown>>(name: string): Unit<Tools> {
  return new Unit<Tools>(name);
}

// ---- example ----

const commented = channel<string>("commented");
const edited = channel<string>("edited");
const overwritten = channel<string>("overwritten");
const moved = channel<string[]>("moved");
const commentAdded = channel<string>("comment_added");

type CommentCreated = { type: "comment.created"; entity: { id: string }; data: { page_id: string } };

export const notion = unit<NotionTools>("notion")
  .input<CommentCreated>("comment.created", (e) => commentAdded(e.data.page_id))
  .output("notion-create-comment", (a) => commented(a.page_id))
  .output("notion-update-page", (a) =>
    a.command === "replace_content" ? overwritten(a.page_id) : edited(a.page_id),
  )
  .output("notion-move-pages", (a) => moved(a.page_or_database_ids))
  .hide("notion-search", "notion-fetch", "notion-get-users", "notion-get-self");
