// Writes transfer.yaml: one CEL rule per amount from $10 to $100 in $10 notes, because a unit's
// events are fixed names (send.5 ... send.100) and the policy needs to know each amount. Anything
// else (more than $100 at once) is the fallback, oversize. Notes keep the unit to 10 rules, which
// the CEL verifier proves pairwise disjoint in seconds at every machine up (a rule per dollar, 100
// rules, took 86 s).
//   node website/game/complier/gen-unit.mjs
import { writeFileSync } from "node:fs";

const LIMIT_DOLLARS = 100;
const NOTE_DOLLARS = 10;
const rules = [];
for (let d = NOTE_DOLLARS; d <= LIMIT_DOLLARS; d += NOTE_DOLLARS) {
  rules.push(`    send_${d}:\n      when: amount_cents == ${d * 100}\n      emit: send.${d}\n      value: string(amount_cents)`);
}
const yaml = `# Generated by gen-unit.mjs; do not edit by hand.
# The game's one effectful tool, send_fake_money, as complier events: a transfer of exactly $d is
# send.d (d = ${NOTE_DOLLARS}, ${2 * NOTE_DOLLARS}, ..., ${LIMIT_DOLLARS}); any larger transfer is oversize. The game's server only
# calls this after the shared input check (amount_cents a positive whole number of $${NOTE_DOLLARS} notes, at most $10,000),
# which the assumption states, so the CEL verifier proves the rules over exactly those inputs.
service: fakebank/service.yaml

translate:
  tools: [send_fake_money]
  schema:
    amount_cents: int
  assumption: "amount_cents > 0 && amount_cents <= 1000000 && amount_cents % ${NOTE_DOLLARS * 100} == 0"
  rules:
${rules.join("\n")}
  fallback:
    emit: oversize
    value: string(amount_cents)

  results:
    default: "ok ? 'done' : 'failed'"
hidden: [get_fake_balance]
`;
writeFileSync(new URL("./transfer.yaml", import.meta.url), yaml);
