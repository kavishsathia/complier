// Builds compiled.ts, the pattern pages' data: the pattern library and each example spec as they are in
// patterns/, and each example's policy as FDR compiled it (the automaton complier's daemon walks).
// The pages' animations walk these automata, so they show what the daemon would do.
//
//   node website/app/patterns/_data/build.mjs
//
// Needs complier-fdr (fdr/build-complier-fdr.sh, against your licensed FDR). patterns.test.ts checks
// compiled.ts is up to date.

import { execFileSync } from "node:child_process";
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, "../../../..");
const driver = join(root, "fdr/build/complier-fdr");

export function compile(spec) {
  let out;
  try {
    out = execFileSync(driver, ["compile", spec], { encoding: "utf8" });
  } catch (e) {
    out = e.stdout;
  }
  const result = JSON.parse(out);
  if (!result.admitted) throw new Error(`${spec} isn't admitted: ${out}`);
  const { root: start, transitions } = result.automaton;
  const raw = result.automaton.states.map(() => ({}));
  for (const t of transitions) raw[t.from][t.event] = t.to;
  return { roles: result.roles, acts: result.acts, automaton: canonical(raw, start) };
}

// FDR numbers the states differently from run to run; renumbered breadth first from the root, taking
// each state's events in name order, the same policy always gives the same automaton.
function canonical(raw, start) {
  const number = new Map([[start, 0]]);
  const order = [start];
  for (let i = 0; i < order.length; i++) {
    for (const event of Object.keys(raw[order[i]]).sort()) {
      const to = raw[order[i]][event];
      if (!number.has(to)) {
        number.set(to, order.length);
        order.push(to);
      }
    }
  }
  const edges = order.map((s) => Object.fromEntries(Object.keys(raw[s]).sort().map((e) => [e, number.get(raw[s][e])])));
  return { root: 0, edges };
}

export function build() {
  const dir = join(root, "patterns/examples");
  const examples = {};
  for (const file of readdirSync(dir).filter((f) => f.endsWith(".csp")).sort()) {
    const slug = file.replace(/\.csp$/, "");
    const spec = join(dir, file);
    examples[slug] = { spec: readFileSync(spec, "utf8"), ...compile(spec) };
  }
  const library = readFileSync(join(root, "patterns/patterns.csp"), "utf8");
  return { library, examples };
}

export function source(data) {
  return `// Generated by build.mjs from patterns/: don't edit. The pattern library, each example spec, and
// each example's policy as FDR compiled it.

export type Automaton = { root: number; edges: Record<string, number>[] };
export type Example = { spec: string; roles: string[]; acts: string[]; automaton: Automaton };

export const LIBRARY: string = ${JSON.stringify(data.library)};

export const EXAMPLES: Record<string, Example> = ${JSON.stringify(data.examples)};
`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeFileSync(join(here, "compiled.ts"), source(build()));
  console.log("wrote website/app/patterns/_data/compiled.ts");
}
